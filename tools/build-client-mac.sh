#!/usr/bin/env bash
# Build a moonlight-qt worktree for macOS with Homebrew Qt 6, bundle Qt and the Homebrew
# libraries into the .app with macdeployqt, normalize/audit Mach-O load paths, and sign it.
#
# usage: tools/build-client-mac.sh <moonlight-qt-worktree> [--clean]
#
# Output: build/<worktree-name>/app/Moonlight.app (out of tree, release, no debug info).
# Requires: Command Line Tools, Homebrew qtbase/qtdeclarative/qtsvg, sdl2, sdl2_ttf, ffmpeg,
# opus, openssl, pkg-config. Set MAKE_JOBS to change the parallelism (default 6).
# Set MAC_CODESIGN_IDENTITY to override signing identity (defaults to the first valid
# "* Local Signing" identity in the keychain if present, else ad-hoc "-").
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/.." && pwd)
# Serialize Mac client builds across agents/sessions: the disk is small and builds are heavy.
if [[ -z "${SDS_MAC_BUILD_LOCKED:-}" ]]; then
    mkdir -p "$ROOT/build"
    exec env SDS_MAC_BUILD_LOCKED=1 /usr/bin/lockf -k "$ROOT/build/.mac-build.lock" "$0" "$@"
fi
SRC=${1:?usage: $0 <moonlight-qt-worktree> [--clean]}
SRC=$(cd "$SRC" && pwd)
NAME=$(basename "$SRC")
OUT="$ROOT/build/$NAME"
JOBS=${MAKE_JOBS:-6}
MIN_FREE_MB=2048

QMAKE=${QMAKE:-/opt/homebrew/bin/qmake6}
MACDEPLOYQT=${MACDEPLOYQT:-/opt/homebrew/bin/macdeployqt}

check_space() {
    local avail_mb
    avail_mb=$(( $(df -k "$HOME" | awk 'NR==2 {print $4}') / 1024 ))
    if (( avail_mb < MIN_FREE_MB )); then
        echo "error: only ${avail_mb} MB free on the data volume (need ${MIN_FREE_MB} MB); stopping before: $1" >&2
        exit 3
    fi
    echo "-- ${avail_mb} MB free before: $1"
}

[[ -f "$SRC/moonlight-qt.pro" ]] || { echo "error: $SRC is not a moonlight-qt checkout" >&2; exit 2; }
"$ROOT/tools/ensure-mac-deps.sh" "$SRC"
[[ -f "$SRC/moonlight-common-c/moonlight-common-c/src/Limelight.h" ]] || {
    echo "error: moonlight-common-c submodule is not checked out in $SRC" >&2; exit 2; }

if [[ "${2:-}" == "--clean" ]]; then
    rm -rf "$OUT"
fi

OPENSSL_PKGCONFIG="/opt/homebrew/opt/openssl/lib/pkgconfig"
if [[ ! -d "$OPENSSL_PKGCONFIG" && -d "/usr/local/opt/openssl/lib/pkgconfig" ]]; then
    OPENSSL_PKGCONFIG="/usr/local/opt/openssl/lib/pkgconfig"
fi
export PKG_CONFIG_PATH="${OPENSSL_PKGCONFIG}${PKG_CONFIG_PATH:+:$PKG_CONFIG_PATH}"

check_space "qmake"
# app.pro copies Info.plist into its output directory while qmake runs, so it must exist
mkdir -p "$OUT/app"
cd "$OUT"

# globaldefs.pri forces debug info (CONFIG += force_debug_info); remove it after the
# project files are read, and empty the *_WITH_DEBUGINFO flags as a second guard.
"$QMAKE" -r "$SRC/moonlight-qt.pro" \
    CONFIG+=disable-prebuilts CONFIG+=disable-x11 CONFIG+=disable-wayland CONFIG+=release \
    "QMAKE_CFLAGS_RELEASE_WITH_DEBUGINFO=-O2" "QMAKE_CXXFLAGS_RELEASE_WITH_DEBUGINFO=-O2" \
    "QMAKE_LFLAGS_RELEASE_WITH_DEBUGINFO=" \
    -after "CONFIG-=force_debug_info"

# Refuse to build with debug info: it does not fit on this machine's disk. Only the release
# Makefiles matter (Makefile.Debug is generated by debug_and_release but never built).
GFLAG_RE='^(CFLAGS|CXXFLAGS|OBJECTIVE_CFLAGS)[[:space:]]*=.*[[:space:]]-g([[:space:]]|$)'
[[ -n "$(find . -name Makefile.Release -print -quit)" ]] || { echo "error: no Makefile.Release generated" >&2; exit 4; }
if grep -rqsE "$GFLAG_RE" --include='Makefile.Release' .; then
    echo "error: generated release Makefiles still contain -g:" >&2
    grep -rnsE "$GFLAG_RE" --include='Makefile.Release' . | head >&2
    exit 4
fi

check_space "make"
make -j"$JOBS" release

APP="$OUT/app/Moonlight.app"
[[ -d "$APP" ]] || { echo "error: $APP was not produced" >&2; exit 5; }

check_space "macdeployqt"
"$MACDEPLOYQT" "$APP" -qmldir="$SRC/app/gui" -always-overwrite

# SDL2-compat opens SDL3 with dlopen(), so macdeployqt cannot discover that runtime
# through Mach-O load commands. Stage it before deployment stamping and signing.
python3 -I "$ROOT/tools/bundle-sdl-runtime.py" "$APP"

STAMP_ARGS=()
if [[ "${SDS_REQUIRE_CLEAN_SOURCE:-0}" == "1" ]]; then
    STAMP_ARGS+=(--require-clean)
fi
python3 -I "$ROOT/tools/stamp-client-bundle.py" "$SRC" "$APP" ${STAMP_ARGS[@]+"${STAMP_ARGS[@]}"}

# Normalize external LC_ID_DYLIBs, strip external/bundle-escaping LC_RPATHs, and enforce a
# strict pre-signing Mach-O audit across all architectures.
python3 -I - "$APP" <<'PYEOF'
import os
import subprocess
import sys
from pathlib import Path

app = Path(sys.argv[1]).resolve(strict=True)
thin_magics = {b"\xcf\xfa\xed\xfe", b"\xfe\xed\xfa\xcf", b"\xce\xfa\xed\xfe", b"\xfe\xed\xfa\xce"}
fat_magics = {
    b"\xca\xfe\xba\xbe": "big",
    b"\xbe\xba\xfe\xca": "little",
    b"\xca\xfe\xba\xbf": "big",
    b"\xbf\xba\xfe\xca": "little",
}


def is_macho(path: Path) -> bool:
    if path.is_symlink() or not path.is_file():
        return False
    with path.open("rb") as f:
        hdr = f.read(8)
    if len(hdr) < 4:
        return False
    magic = hdr[:4]
    if magic in thin_magics:
        return True
    endian = fat_magics.get(magic)
    if endian and len(hdr) == 8:
        nfat = int.from_bytes(hdr[4:8], endian)
        return 0 < nfat < 20
    return False


def parse_macho(path: Path):
    out = subprocess.check_output(["otool", "-l", "-arch", "all", str(path)], text=True)
    lines = out.splitlines()
    ids, loads, rpaths = [], [], []
    cmds = {
        "cmd LC_ID_DYLIB",
        "cmd LC_LOAD_DYLIB",
        "cmd LC_LOAD_WEAK_DYLIB",
        "cmd LC_REEXPORT_DYLIB",
        "cmd LC_RPATH",
    }
    i = 0
    while i < len(lines):
        s = lines[i].strip()
        if s in cmds:
            cmd = s.split()[1]
            val = None
            for j in range(i + 1, min(i + 12, len(lines))):
                lj = lines[j].strip()
                if lj.startswith(("cmd ", "Load command ", "Mach header")):
                    break
                if lj.startswith(("name ", "path ")):
                    val = lj[5:].rsplit(" (offset ", 1)[0]
                    break
            if val is not None:
                if cmd == "LC_ID_DYLIB":
                    ids.append(val)
                elif cmd == "LC_RPATH":
                    rpaths.append(val)
                else:
                    loads.append((cmd, val))
        i += 1
    return ids, loads, rpaths


def resolve_at_path(image: Path, val: str) -> Path | None:
    if val == "@loader_path" or val.startswith("@loader_path/"):
        base = image.parent
        rel = val[len("@loader_path"):].lstrip("/")
    elif val == "@executable_path" or val.startswith("@executable_path/"):
        base = app / "Contents/MacOS"
        rel = val[len("@executable_path"):].lstrip("/")
    else:
        return None
    return Path(os.path.normpath(base / rel))


def is_in_bundle(target: Path | None) -> bool:
    return target is not None and (target == app or target.is_relative_to(app))


def ensure_writable(path: Path) -> None:
    if not os.access(path, os.W_OK):
        os.chmod(path, path.stat().st_mode | 0o200)


machos = [p for p in sorted(app.rglob("*")) if is_macho(p)]
if not machos:
    print("error: no Mach-O binaries found in bundle", file=sys.stderr)
    sys.exit(6)

for image in machos:
    ids, _, rpaths = parse_macho(image)
    for id_val in dict.fromkeys(ids):
        if not id_val.startswith("@"):
            ensure_writable(image)
            rel = image.relative_to(app)
            if rel.parts[:2] == ("Contents", "Frameworks"):
                new_id = "@executable_path/../Frameworks/" + "/".join(rel.parts[2:])
            else:
                new_id = "@loader_path/" + image.name
            subprocess.run(["install_name_tool", "-id", new_id, str(image)], check=True)
            break

    for rp in dict.fromkeys(rpaths):
        if not (rp.startswith(("@executable_path/", "@loader_path/")) and is_in_bundle(resolve_at_path(image, rp))):
            ensure_writable(image)
            while True:
                _, _, current_rpaths = parse_macho(image)
                if rp not in current_rpaths:
                    break
                subprocess.run(["install_name_tool", "-delete_rpath", rp, str(image)], check=True)

allowed_load_prefixes = ("@executable_path/", "@loader_path/", "@rpath/", "/System/Library/", "/usr/lib/")
allowed_id_prefixes = ("@executable_path/", "@loader_path/", "@rpath/")
main_exec = app / "Contents/MacOS/Moonlight"
_, _, main_rpaths = parse_macho(main_exec) if main_exec.is_file() else ([], [], [])
main_resolved_rpaths = [p for rp in main_rpaths if (p := resolve_at_path(main_exec, rp)) and is_in_bundle(p)]

failures = []
for image in machos:
    rel = image.relative_to(app)
    ids, loads, rpaths = parse_macho(image)
    resolved_rpaths = [p for rp in rpaths if (p := resolve_at_path(image, rp)) and is_in_bundle(p)]
    search_rpaths = list(dict.fromkeys(resolved_rpaths + main_resolved_rpaths + [app / "Contents/Frameworks"]))

    for id_val in ids:
        if not id_val.startswith(allowed_id_prefixes):
            failures.append(f"{rel}: LC_ID_DYLIB outside bundle namespace -> {id_val}")

    for rp in rpaths:
        if not rp.startswith(("@executable_path/", "@loader_path/")):
            failures.append(f"{rel}: LC_RPATH points outside bundle -> {rp}")
        elif not is_in_bundle(resolve_at_path(image, rp)):
            failures.append(f"{rel}: LC_RPATH escapes bundle -> {rp}")

    for cmd, val in loads:
        if not val.startswith(allowed_load_prefixes):
            failures.append(f"{rel}: {cmd} points outside allowed prefixes -> {val}")
        elif val.startswith(("@executable_path/", "@loader_path/")):
            target = resolve_at_path(image, val)
            if not is_in_bundle(target):
                failures.append(f"{rel}: {cmd} escapes bundle -> {val}")
            elif cmd != "LC_LOAD_WEAK_DYLIB" and not target.exists():
                failures.append(f"{rel}: {cmd} missing target inside bundle -> {val}")
        elif val.startswith("@rpath/") and cmd != "LC_LOAD_WEAK_DYLIB":
            sub = val[len("@rpath/"):]
            if not any((rp_dir / sub).exists() for rp_dir in search_rpaths):
                failures.append(f"{rel}: {cmd} unresolved inside bundle -> {val}")

if failures:
    print("error: pre-signing Mach-O audit failed:", file=sys.stderr)
    for item in failures:
        print("  " + item, file=sys.stderr)
    sys.exit(6)
PYEOF

ENTITLEMENTS=""
for candidate in "$SRC/app/Moonlight.entitlements" "$SRC/app/deploy/mac/Moonlight.entitlements"; do
    if [[ -f "$candidate" ]]; then
        ENTITLEMENTS="$candidate"
        break
    fi
done
[[ -n "$ENTITLEMENTS" ]] || { echo "error: Moonlight.entitlements not found under $SRC/app" >&2; exit 5; }

if [[ -n "${MAC_CODESIGN_IDENTITY:-}" ]]; then
    SIGN_IDENTITY="$MAC_CODESIGN_IDENTITY"
else
    LOCAL_MATCHES=$(security find-identity -v -p codesigning 2>/dev/null | grep -E '"[^"]+ Local Signing"' || true)
    LOCAL_COUNT=$(printf '%s\n' "$LOCAL_MATCHES" | sed '/^$/d' | wc -l | tr -d ' ')
    if [[ "$LOCAL_COUNT" -ge 1 ]]; then
        SIGN_IDENTITY=$(printf '%s\n' "$LOCAL_MATCHES" | awk '{print $2; exit}')
    else
        SIGN_IDENTITY="-"
    fi
fi
echo "-- signing with identity: $SIGN_IDENTITY"

# Inside-out Hardened Runtime signing: deepest nested Mach-Os and bundles first, then $APP.
while IFS= read -r -d '' item; do
    codesign --force --options runtime -s "$SIGN_IDENTITY" "$item"
done < <(python3 -I - "$APP" <<'PYEOF'
import sys
from pathlib import Path

app = Path(sys.argv[1]).resolve(strict=True)
contents = app / "Contents"
bundle_suffixes = {".framework", ".app", ".xpc", ".plugin", ".bundle"}
thin_magics = {b"\xcf\xfa\xed\xfe", b"\xfe\xed\xfa\xcf", b"\xce\xfa\xed\xfe", b"\xfe\xed\xfa\xce"}
fat_magics = {
    b"\xca\xfe\xba\xbe": "big",
    b"\xbe\xba\xfe\xca": "little",
    b"\xca\xfe\xba\xbf": "big",
    b"\xbf\xba\xfe\xca": "little",
}


def is_macho(path: Path) -> bool:
    if path.is_symlink() or not path.is_file():
        return False
    with path.open("rb") as f:
        hdr = f.read(8)
    if len(hdr) < 4:
        return False
    magic = hdr[:4]
    if magic in thin_magics:
        return True
    endian = fat_magics.get(magic)
    if endian and len(hdr) == 8:
        nfat = int.from_bytes(hdr[4:8], endian)
        return 0 < nfat < 20
    return False


def is_bundle_primary_binary(path: Path) -> bool:
    if path == contents / "MacOS/Moonlight":
        return True
    # <Name>.framework/Versions/<V>/<Name>
    if (
        len(path.parts) >= 4
        and path.parent.parent.name == "Versions"
        and path.parent.parent.parent.name == f"{path.name}.framework"
    ):
        return True
    # <Helper>.(app|xpc|plugin|bundle)/Contents/MacOS/<Name>
    if (
        len(path.parts) >= 4
        and path.parent.name == "MacOS"
        and path.parent.parent.name == "Contents"
        and path.parent.parent.parent.suffix in (bundle_suffixes - {".framework"})
    ):
        return True
    return False


targets = []
for path in contents.rglob("*"):
    if path.is_symlink():
        continue
    if path.is_dir() and path.suffix in bundle_suffixes:
        targets.append(path)
    elif is_macho(path) and not is_bundle_primary_binary(path):
        targets.append(path)

targets.sort(key=lambda p: (-len(p.parts), 0 if p.is_file() else 1, str(p)))
for target in targets:
    sys.stdout.buffer.write(str(target).encode("utf-8") + b"\0")
PYEOF
)

codesign --force --options runtime --entitlements "$ENTITLEMENTS" -s "$SIGN_IDENTITY" "$APP"
SIGN_INFO=$(codesign -dv "$APP" 2>&1)
if grep -Fq "TeamIdentifier=not set" <<<"$SIGN_INFO"; then
    # Local self-signed certs and ad-hoc ("-") carry no Apple Team ID,
    # so Hardened Runtime Library Validation blocks loading bundled dylibs unless disabled.
    TMP_ENTITLEMENTS=$(mktemp "$OUT/.entitlements.XXXXXX")
    trap 'rm -f "$TMP_ENTITLEMENTS"' EXIT
    python3 -I - "$ENTITLEMENTS" "$TMP_ENTITLEMENTS" <<'PYEOF'
import plistlib
import sys

with open(sys.argv[1], "rb") as f:
    plist = plistlib.load(f)
plist["com.apple.security.cs.disable-library-validation"] = True
with open(sys.argv[2], "wb") as f:
    plistlib.dump(plist, f)
PYEOF
    codesign --force --options runtime --entitlements "$TMP_ENTITLEMENTS" -s "$SIGN_IDENTITY" "$APP"
    rm -f "$TMP_ENTITLEMENTS"
    trap - EXIT
fi

codesign --verify --deep --strict "$APP"
shasum -a 256 "$APP/Contents/MacOS/Moonlight" > "$OUT/Moonlight-executable.sha256"

du -sh "$APP"
df -h "$HOME" | tail -1
echo "Built $APP"
